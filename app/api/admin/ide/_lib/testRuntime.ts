async function runOneTestType(typeId: TestTypeId, actor: string, ownerId: string): Promise<TestResult> {
  const def = getTestTypeDefinition(typeId)!;
  if (def.status === "NOT_IMPLEMENTED") return runCommandTest(typeId, actor, ownerId); // returns NOT_IMPLEMENTED honestly
  if (def.executionMode === "STATIC_SCAN") {
    if (typeId === "ROUTE_AUTH_TEST") return runRouteAuthTest();
    if (typeId === "REGISTRY_TEST") return runRegistryTest();
    if (typeId === "SECURITY_TEST") return runSecurityTest();
  }
  return runCommandTest(typeId, actor, ownerId);
}

export async function createTestRun(
  actor: string, ownerId: string,
  refs: { sourceChangeSet?: string | null; reviewId?: string | null; queueJobId?: string | null },
  jobId: string | null,
): Promise<TestRun> {
  const testRunId = randomUUID();
  const startedAt = new Date().toISOString();
  const startedMs = Date.now();

  // Real cross-reference validation (never fabricated — a bad
  // sourceChangeSet/reviewId is honestly rejected, not silently accepted).
  let sourceChangeSet: string | null = null;
  let reviewId: string | null = null;
  if (refs.sourceChangeSet) {
    try { getChangeSet(refs.sourceChangeSet, ownerId); sourceChangeSet = refs.sourceChangeSet; }
    catch (e) { if (e instanceof ChangeSetError) throw e; throw e; }
  }
  if (refs.reviewId) {
    try { getChangeSet(refs.reviewId, ownerId); reviewId = refs.reviewId; }
    catch (e) { if (e instanceof ChangeSetError) throw e; throw e; }
  }

  emitEvent(testRunId, jobId, actor, "TEST_STARTED", `real Test Run started, actor ${actor}`);

  const results: TestResult[] = [];
  let primaryExecutionId: string | null = null;
  for (const def of listTestTypes()) {
    const result = await runOneTestType(def.id, actor, ownerId);
    results.push(result);
    if (!primaryExecutionId && result.executionId) primaryExecutionId = result.executionId;
    if (result.status === "FAILED") emitEvent(testRunId, jobId, actor, "TEST_FAILED", `${def.id}: ${result.failures.join("; ") || "real failure, no detail text"}`);
    else if (result.status === "SKIPPED") emitEvent(testRunId, jobId, actor, "TEST_SKIPPED", `${def.id}`);
    else if (result.status === "CANCELLED") emitEvent(testRunId, jobId, actor, "TEST_CANCELLED", `${def.id}`);
    else emitEvent(testRunId, jobId, actor, "TEST_COMPLETED", `${def.id}: ${result.status}`);
  }

  const totals = {
    total: results.length,
    passed: results.filter((r) => r.status === "PASSED").length,
    failed: results.filter((r) => r.status === "FAILED").length,
    skipped: results.filter((r) => r.status === "SKIPPED" || r.status === "CANCELLED").length,
    notImplemented: results.filter((r) => r.status === "NOT_IMPLEMENTED").length,
  };
  const blockingFailures = results.filter((r) => r.status === "FAILED" && r.blocking);
  const blockingReasons = blockingFailures.map((r) => `${r.testTypeId}: ${r.failures[0] ?? "real blocking failure"}`);
  let status: TestRunStatus;
  if (blockingFailures.length > 0) status = "BLOCKED";
  else if (totals.failed > 0) status = "FAILED";
  else status = "PASSED";
  if (blockingFailures.length > 0) emitEvent(testRunId, jobId, actor, "TEST_BLOCKED", blockingReasons.join(" | "));

  const finishedAt = new Date().toISOString();
  const duration = Date.now() - startedMs;
  const suitesCovered = [...new Set(results.map((r) => r.suite))];

  const testRun: TestRun = {
    testRunId, actor, ownerId, sourceChangeSet, reviewId, queueJobId: refs.queueJobId ?? jobId, executionId: primaryExecutionId,
    artifactIds: [], startedAt, finishedAt, duration, status, totals,
    passed: totals.passed, failed: totals.failed, skipped: totals.skipped, notImplemented: totals.notImplemented,
    stale: false, evidence: `real Test Run: ${results.length} Test Type(s) executed, ${totals.passed} passed, ${totals.failed} failed, ${totals.notImplemented} not-implemented`,
    blockingReasons, suitesCovered, results,
  };

  // Real Artifacts (section 11) — TEST_RUN, TEST_REPORT, TEST_SUMMARY,
  // TEST_LOG, TEST_COVERAGE, TEST_FAILURE, and one TEST_EVIDENCE per real
  // Test — all through the same real Artifact Runtime, never a new store.
  const runManifest = createTestArtifact({
    artifactType: "TEST_RUN", content: JSON.stringify({ testRunId, actor, sourceChangeSet, reviewId, queueJobId: testRun.queueJobId, startedAt, finishedAt, duration, status, totals }),
    mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId,
  });
  testRun.artifactIds.push(runManifest.artifactId);

  const report = createTestArtifact({
    artifactType: "TEST_REPORT", content: JSON.stringify(results.map((r) => ({ id: r.id, suite: r.suite, name: r.name, status: r.status, duration: r.duration, evidence: r.evidence, warnings: r.warnings, failures: r.failures }))),
    mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId, parentIds: [runManifest.artifactId],
  });
  testRun.artifactIds.push(report.artifactId);

  const summaryArtifact = createTestArtifact({
    artifactType: "TEST_SUMMARY", content: JSON.stringify({ totals, status, blockingReasons, suitesCovered }),
    mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId, parentIds: [runManifest.artifactId],
  });
  testRun.artifactIds.push(summaryArtifact.artifactId);

  const logText = results.filter((r) => r.output).map((r) => `=== ${r.testTypeId} ===\n${r.output}`).join("\n\n");
  const logArtifact = createTestArtifact({
    artifactType: "TEST_LOG", content: logText || "(no command-based Test Type produced real output)",
    mimeType: "text/plain", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId, parentIds: [runManifest.artifactId],
  });
  testRun.artifactIds.push(logArtifact.artifactId);

  const coverage = createTestArtifact({
    artifactType: "TEST_COVERAGE", content: JSON.stringify(results.map((r) => ({ testTypeId: r.testTypeId, suite: r.suite, status: r.status }))),
    mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId, parentIds: [runManifest.artifactId],
  });
  testRun.artifactIds.push(coverage.artifactId);

  const failureArtifact = createTestArtifact({
    artifactType: "TEST_FAILURE", content: JSON.stringify(results.filter((r) => r.status === "FAILED").map((r) => ({ testTypeId: r.testTypeId, blocking: r.blocking, failures: r.failures, evidence: r.evidence }))),
    mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: testRunId, parentIds: [runManifest.artifactId],
  });
  testRun.artifactIds.push(failureArtifact.artifactId);

  for (const r of results) {
    const evArtifact = createTestArtifact({
      artifactType: "TEST_EVIDENCE",
      content: JSON.stringify({ testTypeId: r.testTypeId, command: r.command, exitCode: r.exitCode, duration: r.duration, executionId: r.executionId, checksum: r.checksum, stdoutStderr: r.output.slice(0, 20_000) }),
      mimeType: "application/json", actor, ownerId, testRunId, jobId, sourceHash: null, generatedFrom: r.id, parentIds: [runManifest.artifactId],
    });
    r.artifacts.push(evArtifact.artifactId);
    testRun.artifactIds.push(evArtifact.artifactId);
  }

  emitEvent(testRunId, jobId, actor, "TEST_REPORT_CREATED", `real TEST_REPORT artifact ${report.artifactId}`);

  testRuns.set(testRunId, testRun);
  evictOld(ownerId);
  return testRun;
}

export function getTestRun(testRunId: string, ownerId: string): TestRun {
  const run = testRuns.get(testRunId);
  if (!run) throw new TestPipelineError("TEST_RUN_NOT_FOUND", "no Test Run with that id");
  if (run.ownerId !== ownerId) throw new TestPipelineError("TEST_RUN_NOT_OWNED", "this Test Run belongs to a different session");
  return run;
}
export function listTestRuns(ownerId: string): TestRun[] {
  return [...testRuns.values()].filter((t) => t.ownerId === ownerId).sort((a, b) => b.startedAt.localeCompare(a.startedAt));
}

export async function rerunTestRun(testRunId: string, ownerId: string, actor: string, jobId: string | null): Promise<TestRun> {
  const prior = getTestRun(testRunId, ownerId);
  return createTestRun(actor, ownerId, { sourceChangeSet: prior.sourceChangeSet, reviewId: prior.reviewId, queueJobId: prior.queueJobId }, jobId);
}

