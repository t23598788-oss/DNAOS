const testRuns = new Map<string, TestRun>();
const MAX_TEST_RUN_HISTORY = 50;
const testRunEvents: TestRunEvent[] = [];
const MAX_EVENTS = 2000;

function emitEvent(testRunId: string, jobId: string | null, actor: string, type: TestRunEventType, evidence: string) {
  testRunEvents.push({ eventId: randomUUID(), testRunId, jobId, actor, timestamp: new Date().toISOString(), type, evidence });
  while (testRunEvents.length > MAX_EVENTS) testRunEvents.shift();
}
export function listTestRunEvents(limit = 200): TestRunEvent[] {
  return testRunEvents.slice(-limit).reverse();
}
function evictOld(ownerId: string) {
  const owned = [...testRuns.values()].filter((t) => t.ownerId === ownerId);
  const overflow = owned.length - MAX_TEST_RUN_HISTORY;
  if (overflow <= 0) return;
  const sorted = owned.sort((a, b) => a.startedAt.localeCompare(b.startedAt));
  for (let i = 0; i < overflow; i++) testRuns.delete(sorted[i].testRunId);
}

