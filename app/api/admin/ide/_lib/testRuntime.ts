let factoryMappingCache: { modules: Record<string, { factoryOwner: string; capability: string }> } | null | undefined;
function loadFactoryMappingSafe(): { modules: Record<string, { factoryOwner: string; capability: string }> } | null {
  if (factoryMappingCache !== undefined) return factoryMappingCache;
  let result: { modules: Record<string, { factoryOwner: string; capability: string }> } | null = null;
  try {
    result = JSON.parse(readFileSync(path.join(WORKSPACE_ROOT, "registry/factory-mapping.json"), "utf-8"));
  } catch { result = null; }
  factoryMappingCache = result;
  return result;
}
