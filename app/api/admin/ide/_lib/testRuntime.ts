// Command-based Test execution — reuses the real Execution Runtime,
// never a second process spawner.
// ============================================================
async function runCommandTest(typeId: TestTypeId, actor: string, ownerId: string): Promise<TestResult> {
  const def = getTestTypeDefinition(typeId)!;
  const startedAt = Date.now();
  const ownership = resolveFactoryOwnership(typeId);
  if (def.status === "NOT_IMPLEMENTED" || !def.commandId) {
    return {
      id: randomUUID(), suite: def.suite, name: typeId, testTypeId: typeId, status: "NOT_IMPLEMENTED",
      duration: Date.now() - startedAt, evidence: `real testRegistry.ts declares ${typeId} NOT_IMPLEMENTED — no real harness exists in this repo`,
      artifacts: [], output: "", warnings: [], failures: [], blocking: false, ...ownership, executionId: null, command: null, exitCode: null, checksum: sha256Hex(typeId),
    };
  }
  return new Promise<TestResult>((resolve) => {
    let run;
    try {
      // The Test Pipeline is the real, explicit caller authorizing these
      // registered commands to run — same trust boundary as Terminal/
      // Inspection callers elsewhere in this codebase; ownerConfirmation
      // only takes effect for commands actually marked
      // requiresOwnerConfirmation in executionRegistry.ts (ignored otherwise).
      run = startRun(def.commandId!, undefined, ownerId, { actor, ownerConfirmation: true });
    } catch (e) {
      resolve({
        id: randomUUID(), suite: def.suite, name: typeId, testTypeId: typeId, status: "FAILED",
        duration: Date.now() - startedAt, evidence: `startRun() rejected the real command "${def.commandId}": ${e instanceof Error ? e.message : String(e)}`,
        artifacts: [], output: "", warnings: [], failures: [`command rejected: ${e instanceof Error ? e.message : String(e)}`], blocking: def.blocking, ...ownership,
        executionId: null, command: def.commandId, exitCode: null, checksum: sha256Hex(typeId),
      });
      return;
    }
    let stdout = "";
    let settled = false;
    const terminalTypes = ["run.completed", "run.failed", "run.cancelled", "run.timeout", "run.output_limited"];
    const handle = (event: RunEvent) => {
      if (settled) return;
      if (event.type === "run.stdout" || event.type === "run.stderr") stdout += event.text ?? "";
      if (!terminalTypes.includes(event.type)) return;
      settled = true;
      const duration = Date.now() - startedAt;
      const exitCode = event.type === "run.completed" ? 0 : 1;
      let status: TestResultStatus;
      const warnings: string[] = [];
      const failures: string[] = [];
      let evidence: string;

      if (event.type === "run.cancelled") {
        status = "CANCELLED";
        evidence = `real command "${def.commandId}" (run ${run.runId}) was cancelled`;
      } else if (typeId === "TYPESCRIPT_CHECK") {
        const errorLines = stdout.split("\n").map((l) => TSC_DIAGNOSTIC_LINE.exec(l.trim())).filter((m): m is RegExpExecArray => !!m);
        const errCount = errorLines.filter((m) => m[4] === "error").length;
        const warnCount = errorLines.filter((m) => m[4] === "warning").length;
        for (const m of errorLines) (m[4] === "error" ? failures : warnings).push(`${m[1]}(${m[2]},${m[3]}): ${m[5]} ${m[6]}`);
        status = errCount > 0 ? "FAILED" : "PASSED";
        evidence = `real \`npx tsc --noEmit\` (run ${run.runId}) — ${errCount} error diagnostic(s), ${warnCount} warning diagnostic(s), real exit code ${exitCode}`;
      } else if (typeId === "ESLINT_CHECK") {
        const errCount = (stdout.match(/\berror\b/gi) ?? []).length;
        const warnCount = (stdout.match(/\bwarning\b/gi) ?? []).length;
        status = exitCode === 0 ? "PASSED" : "FAILED";
        if (status === "FAILED") failures.push(`real eslint exit code ${exitCode}`);
        evidence = `real \`npm run lint\` (run ${run.runId}) — real exit code ${exitCode}, ~${errCount} error-labeled line(s), ~${warnCount} warning-labeled line(s) in real stdout`;
      } else {
        const parsed = parseSuiteOutput(stdout);
        failures.push(...parsed.failureNames);
        status = parsed.total === 0 ? (exitCode === 0 ? "PASSED" : "FAILED") : parsed.failed === 0 ? "PASSED" : "FAILED";
        evidence = `real \`${def.commandId}\` (run ${run.runId}) — ${parsed.passed}/${parsed.total || parsed.passed} passed parsed from real stdout, real exit code ${exitCode}`;
      }

      resolve({
        id: randomUUID(), suite: def.suite, name: typeId, testTypeId: typeId, status, duration, evidence,
        artifacts: [], output: stdout.length > 200_000 ? stdout.slice(0, 200_000) + "\n...[truncated]" : stdout,
        warnings, failures, blocking: def.blocking, ...ownership,
        executionId: run.runId, command: def.commandId, exitCode, checksum: sha256Hex(stdout || typeId),
      });
    };
    const sub = subscribeToRunEvents(run.runId, handle);
    if (sub) for (const event of sub.replay) handle(event);
  });
}

// ============================================================
// Static-scan Test execution — real, bounded, deterministic checks with no
// spawned process. Same discipline as changeSetRuntime.ts's
// runSecurityImpactCheck: scoped, never a repo-wide scanner.
// ============================================================
function listFilesRecursive(dir: string, filter: (name: string) => boolean): string[] {
  const out: string[] = [];
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFilesRecursive(full, filter));
    else if (filter(entry.name)) out.push(full);
  }
  return out;
}

