function resolveFactoryOwnership(typeId: TestTypeId): { factoryOwner: string | null; capability: string | null; moduleId: string | null } {
  const file = TEST_TYPE_OWNER_FILE[typeId];
  if (!file) return { factoryOwner: null, capability: null, moduleId: null };
  const fm = loadFactoryMappingSafe();
  const entry = fm?.modules?.[file];
  if (!entry) return { factoryOwner: "UNKNOWN", capability: null, moduleId: file };
  return { factoryOwner: entry.factoryOwner, capability: entry.capability ?? null, moduleId: file };
}

// ============================================================
// Generic PASS/FAIL/summary parsing for this repo's regression scripts —
// every scripts/*-test.ts file this runtime invokes prints
// `${pass?"PASS":"FAIL"}  ${name}` per assertion and a final
// `${passed}/${total} passed` line (verified by reading each script before
// registering its command in testRegistry.ts). Never a fabricated parse —
// if the pattern doesn't match, zero results are reported honestly rather
// than guessed.
// ============================================================
const SUITE_LINE = /^(PASS|FAIL)\s\s(.+)$/;
const SUITE_SUMMARY = /(\d+)\/(\d+)\s+passed/;
function parseSuiteOutput(stdout: string): { passed: number; failed: number; total: number; failureNames: string[] } {
  let passed = 0, failed = 0;
  const failureNames: string[] = [];
  for (const line of stdout.split("\n")) {
    const m = SUITE_LINE.exec(line.trim());
    if (!m) continue;
    if (m[1] === "PASS") passed++;
    else { failed++; failureNames.push(m[2]); }
  }
  const summary = SUITE_SUMMARY.exec(stdout);
  const total = summary ? parseInt(summary[2], 10) : passed + failed;
  return { passed, failed, total, failureNames };
}
const TSC_DIAGNOSTIC_LINE = /^(.+?)\((\d+),(\d+)\): (error|warning) (TS\d+): (.+)$/;

