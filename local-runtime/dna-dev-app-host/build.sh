#!/bin/bash
# หน้าที่: builds DNA DEV.app from THIS folder's governed source and emits a
# real BuildManifest (see ./types.ts). Follows the proven assembly pattern from
# connections/voice-command/app-host/build.sh — manual Contents/ layout, xattr
# clean, ad-hoc codesign with a stable CFBundleIdentifier — WITHOUT importing
# that capability's internals (Capability Folder Law rule 9).
#
# The build output goes to ./build/ inside this capability folder. Installing it
# to the Desktop is a SEPARATE, authorized step: ./install.sh.
#
# Every hash here is COMPUTED from real bytes on disk. Nothing is asserted.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$DIR/build"
APP="$OUT/DNA DEV.app"
BUILD_ID="build-$(date -u +%Y%m%dT%H%M%SZ)-$(head -c 6 /dev/urandom | xxd -p)"

# The launch URL is the REGISTERED_REMOTE circuit endpoint from the Railway
# adapter JSONL (optional provider backing). Core config.ts resolves the same id.
ROOT="$(cd "$DIR/../.." && pwd)"
LAUNCH_URL="$(node -e "
const fs = require('fs');
const p = process.argv[1];
for (const line of fs.readFileSync(p, 'utf8').split(/\n/)) {
  if (!line.trim()) continue;
  const j = JSON.parse(line);
  if (j.endpoint_id === 'endpoint://dna-os-circuit/public' && j.status === 'ACTIVE') {
    process.stdout.write(j.address);
    process.exit(0);
  }
}
process.exit(1);
" "$ROOT/connections/railway/data/runtime-endpoints.jsonl")"
if [ -z "$LAUNCH_URL" ]; then
  echo "build: FAILED — could not read the canonical url from config.ts" >&2
  exit 1
fi

rm -rf "$OUT"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# launcher: template -> real executable, with the URL and build stamp baked in
sed -e "s|@@LAUNCH_URL@@|$LAUNCH_URL|" \
    -e "s|@@BUILD_STAMP@@|generated by local-runtime/dna-dev-app-host/build.sh · build_id=$BUILD_ID|" \
    "$DIR/launcher.template.sh" > "$APP/Contents/MacOS/launcher"
chmod +x "$APP/Contents/MacOS/launcher"

cp "$DIR/Info.plist" "$APP/Contents/Info.plist"

# Icon is OPTIONAL and only used when a governed copy exists in this folder.
# The build never reaches outside the capability boundary to fetch one.
if [ -f "$DIR/app.icns" ]; then
  cp "$DIR/app.icns" "$APP/Contents/Resources/app.icns"
  ICON_STATE="governed app.icns included"
else
  ICON_STATE="no governed app.icns present — bundle uses the system default icon"
fi

xattr -cr "$APP" 2>/dev/null || true
codesign --sign - --force --identifier dev.dnaos.dna-dev "$APP" >/dev/null 2>&1 || true

# --- real measured hashes ---
launcher_sha="$(shasum -a 256 "$APP/Contents/MacOS/launcher" | awk '{print $1}')"
bundle_sha="$(cd "$APP" && find . -type f -print0 | sort -z | xargs -0 shasum -a 256 | shasum -a 256 | awk '{print $1}')"
src_json=""
for f in launcher.template.sh Info.plist config.ts types.ts contract.ts; do
  h="$(shasum -a 256 "$DIR/$f" | awk '{print $1}')"
  src_json="$src_json    \"$f\": \"$h\",\n"
done
src_json="${src_json%,\\n}"

cat > "$OUT/build-manifest.json" <<MANIFEST
{
  "build_id": "$BUILD_ID",
  "capability_id": "dna-dev-app-host",
  "owner_folder": "local-runtime/dna-dev-app-host/",
  "source_hashes": {
$(printf "$src_json")
  },
  "artifact_launcher_sha256": "$launcher_sha",
  "artifact_bundle_sha256": "$bundle_sha",
  "launch_target": { "url": "$LAUNCH_URL", "runtime_kind": "REGISTERED_REMOTE", "service_id": "dna-os-circuit" },
  "icon": "$ICON_STATE",
  "built_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
MANIFEST

echo "BUILD_ID              $BUILD_ID"
echo "artifact              $APP"
echo "launch url            $LAUNCH_URL"
echo "launcher sha256       $launcher_sha"
echo "bundle   sha256       $bundle_sha"
echo "icon                  $ICON_STATE"
echo "manifest              $OUT/build-manifest.json"
