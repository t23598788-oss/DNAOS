/**
 * หน้าที่: the real test for `local-runtime/dna-dev-app-host/`. Drives the REAL
 * exported contract and inspects the REAL built artifact on disk — no mocks, no
 * fixtures standing in for the bundle.
 *
 * The cases that matter are C1 and C3: the launcher must NOT open the repository
 * folder in Finder (the exact 2026-08-24 defect this capability exists to fix),
 * and the built artifact must point at the canonical Railway runtime rather than
 * silently at localhost.
 *
 * Run: npx tsx local-runtime/dna-dev-app-host/tests/dna-dev-app-host.test.ts
 * (build first: ./local-runtime/dna-dev-app-host/build.sh)
 */

import { CANONICAL_TARGET, LOCAL_TARGET, resolveLaunchTarget } from "../contract";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

declare const process: { exitCode?: number; cwd(): string };
declare const console: { log(...a: unknown[]): void };

let passed = 0, failed = 0;
function check(name: string, cond: boolean, detail?: unknown): void {
  if (cond) { passed++; console.log(`PASS  ${name}`); }
  else { failed++; console.log(`FAIL  ${name}\n      ${JSON.stringify(detail)}`); }
}

const HERE = join(process.cwd(), "local-runtime/dna-dev-app-host");
const BUILT = join(HERE, "build/DNA DEV.app");
const BUILT_LAUNCHER = join(BUILT, "Contents/MacOS/launcher");

function main(): void {
  // ---- A. the declared target is the canonical Railway runtime ----
  check("A1. canonical target is the Railway deployment, not localhost",
    CANONICAL_TARGET.runtime_kind === "RAILWAY_DEPLOYMENT" && CANONICAL_TARGET.url.startsWith("https://"), CANONICAL_TARGET);
  check("A2. canonical target names the real Railway service from .railway/railway.ts",
    CANONICAL_TARGET.railway_service === "dna-os-circuit");
  check("A3. the target carries the evidence that proves it was discovered, not chosen",
    CANONICAL_TARGET.evidence.length >= 4 && CANONICAL_TARGET.evidence.some((e) => e.includes(".railway/railway.ts")));

  // ---- B. no SILENT localhost fallback (the Owner's explicit rule) ----
  check("B1. resolveLaunchTarget defaults to the Railway deployment",
    resolveLaunchTarget("RAILWAY_DEPLOYMENT").runtime_kind === "RAILWAY_DEPLOYMENT");
  check("B2. the local target exists but is NAMED, never implied",
    LOCAL_TARGET.runtime_kind === "LOCAL_DEVELOPMENT" && resolveLaunchTarget("LOCAL_DEVELOPMENT").url === LOCAL_TARGET.url);
  check("B3. the two targets are genuinely different runtimes",
    CANONICAL_TARGET.url !== LOCAL_TARGET.url);

  // ---- C. THE REGRESSION: the built artifact must never open Finder ----
  if (!existsSync(BUILT_LAUNCHER)) {
    check("C0. built artifact exists (run ./build.sh first)", false, BUILT_LAUNCHER);
  } else {
    const launcher = readFileSync(BUILT_LAUNCHER, "utf8");
    check("C1. the built launcher does NOT open the repository folder (the 2026-08-24 defect)",
      !launcher.includes("DNA-OS-INFRASTRUCTURE\"") && !/open\s+"\/Users\/[^"]*DNA-OS-INFRASTRUCTURE/.test(launcher), launcher.slice(0, 160));
    check("C2. the built launcher opens a UI, not a directory",
      launcher.includes("--app=") || launcher.includes("exec open \"$DNA_DEV_URL\""));
    check("C3. the built launcher carries the CANONICAL Railway url, baked from config.ts",
      launcher.includes(CANONICAL_TARGET.url), (launcher.match(/DNA_DEV_URL="[^"]*"/) ?? [])[0]);
    check("C4. the built launcher does NOT silently reference localhost",
      !launcher.includes("127.0.0.1") && !launcher.includes("localhost"));
    check("C5. the built launcher declares itself a generated artifact, not source",
      /GENERATED by|build_id=/.test(launcher));
  }

  // ---- D. the bundle is a real, well-formed .app ----
  check("D1. built bundle has Contents/Info.plist", existsSync(join(BUILT, "Contents/Info.plist")));
  check("D2. built launcher is the CFBundleExecutable named in Info.plist",
    existsSync(join(BUILT, "Contents/Info.plist")) &&
    readFileSync(join(BUILT, "Contents/Info.plist"), "utf8").includes("<string>launcher</string>"));
  check("D3. bundle identity is preserved (dev.dnaos.dna-dev)",
    existsSync(join(BUILT, "Contents/Info.plist")) &&
    readFileSync(join(BUILT, "Contents/Info.plist"), "utf8").includes("dev.dnaos.dna-dev"));

  // ---- E. provenance is measured, never asserted ----
  const manifestPath = join(HERE, "build/build-manifest.json");
  if (!existsSync(manifestPath)) {
    check("E0. build manifest exists", false, manifestPath);
  } else {
    const m = JSON.parse(readFileSync(manifestPath, "utf8")) as {
      build_id: string; artifact_launcher_sha256: string; artifact_bundle_sha256: string;
      source_hashes: Record<string, string>; launch_target: { url: string };
    };
    check("E1. manifest records a real build_id", typeof m.build_id === "string" && m.build_id.startsWith("build-"));
    check("E2. manifest records source hashes for the governed inputs",
      Object.keys(m.source_hashes).includes("launcher.template.sh") && Object.keys(m.source_hashes).includes("config.ts"));
    check("E3. manifest's launch_target matches config.ts — the artifact cannot point elsewhere",
      m.launch_target.url === CANONICAL_TARGET.url, m.launch_target);
    check("E4. manifest hashes are 64-hex sha256, i.e. really computed",
      /^[0-9a-f]{64}$/.test(m.artifact_launcher_sha256) && /^[0-9a-f]{64}$/.test(m.artifact_bundle_sha256));
  }
}

main();
console.log(`\n${passed} passed, ${failed} failed`);
if (failed > 0) process.exitCode = 1;
