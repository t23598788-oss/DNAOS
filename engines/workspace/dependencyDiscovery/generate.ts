/**
 * Automatic Dependency Discovery orchestrator (Roadmap #46). Runs all 9
 * scanners against the real repository and writes registry/auto-dependency-
 * graph.json. Per owner instruction 2026-08-04: this does NOT delete or
 * replace registry/infra-dependency-graph.json (the hand-maintained seed) —
 * that stays until the auto results are verified. engines/workspace/
 * dependencyRegistry.ts is what actually changes which source is queried
 * first.
 */
import { writeFileSync } from "fs";
import { join } from "path";
import type { DependencyDiscoveryReport, DependencyScannerName } from "@/core/shared/types";
import { ROOT } from "./common";
import { scanTypescriptImports } from "./scanTypescriptImports";
import { scanJsonRegistry } from "./scanJsonRegistry";
import { scanRuntimeCommands } from "./scanRuntimeCommands";
import { scanLaunchAgents } from "./scanLaunchAgents";
import { scanDocker } from "./scanDocker";
import { scanAiModelsRuntime } from "./scanAiModelsRuntime";
import { scanSupabaseFunctions } from "./scanSupabaseFunctions";
import { scanConfigReferences } from "./scanConfigReferences";
import { scanWorkflowReferences } from "./scanWorkflowReferences";

export function generateDependencyGraph(): DependencyDiscoveryReport {
  const scannerCounts: DependencyDiscoveryReport["scanner_counts"] = {} as any;
  const allEdges: DependencyDiscoveryReport["edges"] = [];
  const allUnknowns: DependencyDiscoveryReport["unknowns"] = [];

  function record(name: DependencyScannerName, edges: typeof allEdges, unknowns: typeof allUnknowns) {
    allEdges.push(...edges);
    allUnknowns.push(...unknowns);
    scannerCounts[name] = { edges: edges.length, unknowns: unknowns.length };
  }

  record("typescript_imports", scanTypescriptImports(), []);
  record("json_registry", scanJsonRegistry(), []);
  record("runtime_commands", scanRuntimeCommands(), []);

  const la = scanLaunchAgents();
  record("launchagents", la.edges, la.unknowns);

  const docker = scanDocker();
  record("docker", docker.edges, docker.unknowns);

  const ai = scanAiModelsRuntime();
  record("ai_models_runtime", ai.edges, ai.unknowns);

  record("supabase_functions", scanSupabaseFunctions(), []);

  const cfg = scanConfigReferences();
  record("config_references", cfg.edges, cfg.unknowns);

  const wf = scanWorkflowReferences();
  record("workflow_references", wf.edges, wf.unknowns);

  return {
    generated_at: new Date().toISOString(),
    edges: allEdges,
    unknowns: allUnknowns,
    scanner_counts: scannerCounts,
  };
}

export function writeDependencyGraph(report: DependencyDiscoveryReport): string {
  const outPath = join(ROOT, "registry/auto-dependency-graph.json");
  writeFileSync(outPath, JSON.stringify({
    version: 1,
    policy: "Auto-generated by engines/workspace/dependencyDiscovery/generate.ts (Roadmap #46, owner 2026-08-04) — DO NOT hand-edit. Regenerate via `npx tsx local-runtime/generate-dependency-graph.ts`. Every edge carries real evidence + a confidence score; edges below CONFIDENCE_THRESHOLD (0.6) never appear here, they're in `unknowns` instead. registry/infra-dependency-graph.json (the hand-maintained seed) is kept for comparison, not deleted, per explicit owner instruction pending verification.",
    ...report,
  }, null, 2) + "\n", "utf-8");
  return outPath;
}
