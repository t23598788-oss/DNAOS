/**
 * หน้าที่: the one entry point that runs the whole chain for a batch of
 * already-fetched alert emails, and produces the Owner-facing record the
 * Owner's step 8 asked for.
 *
 *   EMAIL -> parseAlertEmail -> resolveTarget -> assessIncident (live probe)
 *         -> classifyAlert (dedup) -> OwnerIncidentReport
 *
 * WHERE THE AI IS: nowhere in this chain. Parsing, resolution,
 * correlation and dedup are deterministic software; the only external
 * fact used is an HTTP probe this capability performs itself. An AI may
 * later READ an `OwnerIncidentReport` to explain it to the Owner, but it
 * cannot produce, alter, or override one — there is no input on any
 * function here that accepts a model's opinion.
 *
 * WHERE THE AI IS NOT WAITING: this runs over a batch already in hand.
 * Nothing here polls a mailbox, sleeps, or blocks on a human. A caller
 * (worker, cron, CLI) supplies emails and gets finished assessments back.
 *
 * Input: `RawAlertEmail[]` + the currently-open incidents.
 * Output: `runAlertCorrelation`, `OwnerIncidentReport`.
 * Dependency ที่อนุญาต: ./types.ts, ./parse.ts, ./resolve.ts,
 * ./correlate.ts, ./dedup.ts.
 * สิ่งที่ห้ามแตะ: never add a parameter that lets a caller pass in a
 * pre-computed `incident_state` — the state must always come from
 * ./correlate.ts's live observation, or the "email is a claim, not a
 * verdict" rule is dead.
 */

import type { RawAlertEmail, IncidentAssessment, AlertField } from "./types";
import { parseAlertEmail } from "./parse";
import { resolveTarget } from "./resolve";
import { assessIncident } from "./correlate";
import { classifyAlert, type DedupDecision, type OpenIncident } from "./dedup";

/** Exactly the fields the Owner's step 8 asked to be handed up, plus provenance. */
export interface OwnerIncidentReport {
  readonly service: AlertField;
  readonly what_happened: string;
  readonly when: string;
  readonly email_evidence: string;
  readonly current_real_state: string;
  readonly recovered_or_still_failing: "RECOVERED" | "STILL_FAILING" | "UNKNOWN";
  readonly affected_resource: AlertField;
  readonly related_deployment: AlertField;
  readonly recommended_next_software_action: string;
  /**
   * PHASE 5 (Owner). Anything with a money consequence stops here and goes
   * to the Owner. Software may observe, correlate and report a billing
   * failure; it may never pay, retry a charge, change a plan, or authorise
   * spend. Derived from alert_type — not a judgement call.
   */
  readonly decision_required: "OWNER" | "NONE";
  /**
   * Structurally constant `false`. Present in every report so the absence
   * of AI financial authority is an asserted, auditable fact in the record
   * itself, not a claim made in a README that nothing enforces.
   */
  readonly ai_financial_authority: false;
  readonly dedup: DedupDecision;
  readonly assessment: IncidentAssessment;
}

/** Alert classes with a money consequence. Owner decision, always. */
const FINANCIAL_ALERT_TYPES: ReadonlySet<string> = new Set(["BILLING_FAILURE"]);

/**
 * The recommended action is a fixed mapping from the derived state — a
 * lookup, never a suggestion generated by a model. It names the next
 * SOFTWARE step, and deliberately stops short of taking it.
 */
function recommendedAction(assessment: IncidentAssessment): string {
  switch (assessment.incident_state) {
    case "ACTIVE_INCIDENT":
      return `query deployment/runtime evidence for "${assessment.alert.service}" and open a diagnostic work item — the failure is corroborated by a live observation`;
    case "ALERT_HISTORICAL_RECOVERED":
      return "record as historical evidence only — no remediation work item; the service is serving now";
    case "UNRESOLVED_ALERT":
      return `register the provider service "${assessment.alert.service}" in resolve.ts#KNOWN_SERVICES before this alert class can ever be correlated`;
    case "UNVERIFIABLE":
      return `observe and record a real health URL for "${assessment.alert.service}" — correlation cannot judge it until one exists`;
  }
}

/**
 * A financial alert overrides the state-based recommendation: whatever the
 * probe said, the next step is an Owner decision, and it is named as one.
 */
function financialAction(assessment: IncidentAssessment): string {
  return `OWNER DECISION REQUIRED — ${assessment.alert.provider} reported "${assessment.alert.reported_status}". This has a money consequence; software must not pay, retry a charge, change a plan, or authorise spend. Surface to the Owner with the email evidence and stop.`;
}

function stateLabel(assessment: IncidentAssessment): "RECOVERED" | "STILL_FAILING" | "UNKNOWN" {
  if (assessment.incident_state === "ALERT_HISTORICAL_RECOVERED") return "RECOVERED";
  if (assessment.incident_state === "ACTIVE_INCIDENT") return "STILL_FAILING";
  return "UNKNOWN";
}

/**
 * Runs the full chain. Emails are processed in `received_at` order so
 * dedup sees them the way they actually arrived; out-of-order input
 * would otherwise make the first-seen incident arbitrary.
 */
export async function runAlertCorrelation(
  emails: readonly RawAlertEmail[],
  openIncidents: readonly OpenIncident[] = [],
): Promise<readonly OwnerIncidentReport[]> {
  const ordered = [...emails].sort((a, b) => Date.parse(a.received_at) - Date.parse(b.received_at));
  const open: OpenIncident[] = openIncidents.map((incident) => ({ ...incident }));
  const reports: OwnerIncidentReport[] = [];

  for (const email of ordered) {
    const alert = parseAlertEmail(email);
    const target = resolveTarget(alert);
    const assessment = await assessIncident(alert, target);
    const dedup = classifyAlert(alert, assessment.incident_state, open);

    if (dedup.verdict === "NEW_INCIDENT") {
      open.push({
        key: dedup.key,
        first_seen_at: alert.received_at,
        last_seen_at: alert.received_at,
        message_ids: [alert.message_id],
        incident_state: assessment.incident_state,
      });
    } else {
      const index = open.findIndex((incident) => incident.key === dedup.key);
      if (index >= 0) {
        const previous = open[index];
        open[index] = {
          ...previous,
          last_seen_at: alert.received_at,
          message_ids: [...previous.message_ids, alert.message_id],
          incident_state: dedup.verdict === "RECOVERY_NOTICE" ? assessment.incident_state : previous.incident_state,
        };
      }
    }

    reports.push({
      service: alert.service,
      what_happened: `${alert.alert_type} reported by ${alert.provider}`,
      when: alert.received_at,
      email_evidence: alert.raw_message_reference,
      current_real_state: assessment.observation
        ? `${assessment.observation.probe_target} -> ${assessment.observation.detail} (observed ${assessment.observation.observed_at})`
        : "no live observation was possible",
      recovered_or_still_failing: stateLabel(assessment),
      affected_resource: target.repo_path,
      related_deployment: alert.deployment_id,
      recommended_next_software_action: FINANCIAL_ALERT_TYPES.has(alert.alert_type)
        ? financialAction(assessment)
        : recommendedAction(assessment),
      decision_required: FINANCIAL_ALERT_TYPES.has(alert.alert_type) ? "OWNER" : "NONE",
      ai_financial_authority: false,
      dedup,
      assessment,
    });
  }

  return reports;
}
