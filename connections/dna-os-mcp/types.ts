/**
 * หน้าที่: shared types for the DNA OS MCP boundary — tool metadata shape,
 * the capability gate result shape, and the DNA OS identity a caller must
 * supply. Pure type definitions, no logic.
 *
 * Input: none.
 * Output: `McpToolPermissionScope`, `McpToolEvidenceBehavior`,
 * `McpToolMetadata`, `CapabilityGateResult`, `DnaOsAgentIdentity`,
 * `CorrelationTrace`.
 * Dependency ที่อนุญาต: none — a leaf contract.
 * สิ่งที่ห้ามแตะ: never add a field here for a raw secret, connection
 * string, or provider token — this boundary is DNA OS-level contracts
 * only, never Supabase/GitHub/Vercel/Keychain implementation detail.
 */

export type McpToolReadWriteBehavior = "read" | "write";

export type McpToolPermissionScope = "owner-command" | "registry-lookup" | "task-status" | "work-result-ingress" | "system-status" | "local-resource-access";

export type McpToolEvidenceBehavior =
  | "returns command_id/task_id/decision/evidence from the real DNA OS response"
  | "returns a sanitized projection of control/command-router/capability-registry.ts"
  | "returns the real registry row or null, no evidence trail generated by a lookup"
  | "returns the real task/result/evidence trail for an existing task_id"
  | "returns the real handoff record and its dna_os_decision"
  | "returns the real live capability/runtime inventory, each entry with its own evidence array"
  | "returns DNA OS runtime/evidence facts with a DNA_OS_RUNTIME proof envelope"
  | "returns DNA_OS_LOCAL_EXECUTION evidence after Owner-policy local resource authorization"
  | "returns the real registered artifacts (resource_id/capability_id per split piece), the handoff recorded as evidence, and the next decision computed from persisted evidence";

/** Declarative description of one MCP tool — used both to register it and to answer `tools/list` truthfully. */
export interface McpToolMetadata {
  name: string;
  title: string;
  description: string;
  read_write: McpToolReadWriteBehavior;
  permission_scope: McpToolPermissionScope;
  evidence_behavior: McpToolEvidenceBehavior;
  /**
   * The control/command-router/capability-registry.ts capability_id this
   * tool's underlying DNA OS pipeline depends on being REGISTERED +
   * VERIFIED + AVAILABLE, per the MCP Tool Resolver in ./capability-gate.ts.
   * `null` for tools that are core ingress/lookup primitives rather than
   * an optional routed capability — see that file's own docstring for
   * exactly which tools this applies to and why.
   */
  dna_os_capability_id: string | null;
}

export type CapabilityGateStatus = "REGISTERED_VERIFIED_AVAILABLE" | "CAPABILITY_NOT_AVAILABLE" | "NOT_GATED_CORE_PRIMITIVE";

export interface CapabilityGateResult {
  status: CapabilityGateStatus;
  capability_id: string | null;
  reason: string;
}

/**
 * The identity an external agent presents. This is never independently
 * authenticated by the MCP layer — it is forwarded verbatim to DNA OS's
 * real identity/permission boundary (permissions/access-control/,
 * permissions/execution-policy/) via the existing owner-command-http
 * transport, exactly the same `ownerIdentity` shape that transport already
 * accepts from an already-authenticated upstream caller. See
 * ./identity.ts.
 */
export interface DnaOsAgentIdentity {
  id: string;
  email: string;
}

export interface CorrelationTrace {
  correlation_id: string;
  mcp_tool: string;
  dna_os_command_id?: string | null;
  dna_os_task_id?: string | null;
  dna_os_decision_id?: string | null;
  dna_os_evidence_id?: string | null;
}
