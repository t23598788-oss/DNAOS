/**
 * DNA_OS_MCP_CANONICAL_TOOLING_V1 hermetic tests.
 * How to run: npx tsx connections/dna-os-mcp/tests/canonical-tooling.test.ts
 *
 * Uses an injected tool metadata fixture so this suite does not load
 * tool-registry.ts (zod / MCP SDK environment) or the HTTP server.
 */

import {
  resolveToolDescriptor,
  resolveToolGrant,
  requiresOwnerDeviceApproval,
  assertApprovalScopeExact,
  setRegisteredToolsProvider,
  setMcpIngressCheck,
  detectCanonicalToolingDrift,
  type RegisteredToolLike,
} from "../tool-grant";
import { canDiscover, canInvoke, policyFor, type CallerContext } from "../export-policy";
import { UNAUTHENTICATED_CONTEXT } from "../caller-context";
import { CANONICAL_OWNERS } from "../canonical-tool-descriptor";
import { resolveCanonicalToolId, CONCEPTUAL_TOOL_ALIASES } from "../conceptual-tool-aliases";
import { isRawRailwayMcpTool } from "../../../control/owner-client-runtime/ai-queen-grants";

declare const process: { exitCode?: number };
declare const console: { log(...args: unknown[]): void; error(...args: unknown[]): void };

let passed = 0;
let failed = 0;

function assert(condition: boolean, message: string): void {
  if (!condition) throw new Error(message);
}

function check(name: string, body: () => void): void {
  try {
    body();
    passed++;
    console.log(`PASS ${name}`);
  } catch (error) {
    failed++;
    console.error(`FAIL ${name}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

const FIXTURE_TOOLS: readonly RegisteredToolLike[] = [
  { metadata: { name: "submit_command", title: "Submit", description: "Submit Owner command", read_write: "write", permission_scope: "owner-command", evidence_behavior: "returns command_id/task_id/decision/evidence from the real DNA OS response", dna_os_capability_id: null } },
  { metadata: { name: "lookup_capability", title: "Lookup", description: "Lookup capability", read_write: "read", permission_scope: "registry-lookup", evidence_behavior: "returns a sanitized projection of control/command-router/capability-registry.ts", dna_os_capability_id: null } },
  { metadata: { name: "list_capabilities", title: "List", description: "List capabilities", read_write: "read", permission_scope: "registry-lookup", evidence_behavior: "returns a sanitized projection of control/command-router/capability-registry.ts", dna_os_capability_id: null } },
  { metadata: { name: "get_resource", title: "Resource", description: "Get resource", read_write: "read", permission_scope: "registry-lookup", evidence_behavior: "returns the real registry row or null, no evidence trail generated by a lookup", dna_os_capability_id: null } },
  { metadata: { name: "get_task", title: "Task", description: "Get task", read_write: "read", permission_scope: "task-status", evidence_behavior: "returns the real task/result/evidence trail for an existing task_id", dna_os_capability_id: null } },
  { metadata: { name: "submit_work_result", title: "Work result", description: "Submit work result", read_write: "write", permission_scope: "work-result-ingress", evidence_behavior: "returns the real handoff record and its dna_os_decision", dna_os_capability_id: null } },
  { metadata: { name: "get_system_status", title: "Status", description: "System status", read_write: "read", permission_scope: "system-status", evidence_behavior: "returns the real live capability/runtime inventory, each entry with its own evidence array", dna_os_capability_id: null } },
  { metadata: { name: "dna_os.resolve_tool_grant", title: "Grant", description: "Resolve tool grant", read_write: "read", permission_scope: "system-status", evidence_behavior: "returns DNA OS runtime/evidence facts with a DNA_OS_RUNTIME proof envelope", dna_os_capability_id: null } },
  { metadata: { name: "dna_os.inspect_tool_descriptor", title: "Inspect", description: "Inspect descriptor", read_write: "read", permission_scope: "system-status", evidence_behavior: "returns DNA OS runtime/evidence facts with a DNA_OS_RUNTIME proof envelope", dna_os_capability_id: null } },
  { metadata: { name: "dna_os.get_runtime_identity", title: "Runtime", description: "Runtime identity", read_write: "read", permission_scope: "system-status", evidence_behavior: "returns DNA OS runtime/evidence facts with a DNA_OS_RUNTIME proof envelope", dna_os_capability_id: null } },
  { metadata: { name: "dna_os.list_local_resources", title: "Local", description: "List local resources", read_write: "read", permission_scope: "local-resource-access", evidence_behavior: "returns DNA_OS_LOCAL_EXECUTION evidence after Owner-policy local resource authorization", dna_os_capability_id: "local-resource-access" } },
];

const INTERNAL: CallerContext = {
  caller: "INTERNAL_DNA_OS",
  caller_class: "INTERNAL_DNA_OS",
  owner_session_id: null,
  channel: "EXTERNAL",
};

const UNAUTH: CallerContext = UNAUTHENTICATED_CONTEXT;

function main(): void {
  setRegisteredToolsProvider(() => FIXTURE_TOOLS);
  setMcpIngressCheck(() => true);

  check("1. known client can discover granted tools", () => {
    const grant = resolveToolGrant({ caller: INTERNAL });
    assert(grant.status === "GRANTED_SET", grant.reason);
    assert(grant.grants.some((g) => g.tool_id === "lookup_capability"), "lookup");
    assert(grant.secrets_exposed === false, "secrets");
    assert(grant.client_vendor_independent === true, "vendor");
  });

  check("2. unauthorized capability is not exposed", () => {
    const grant = resolveToolGrant({ caller: UNAUTH, requested_tool_id: "submit_command" });
    assert(grant.status === "EMPTY" || grant.grants.every((g) => !g.invokable), "no submit for unauth");
    assert(!canDiscover("submit_command", UNAUTH).allowed, "not discoverable");
  });

  check("3. read-only tool cannot perform write (descriptor)", () => {
    const d = resolveToolDescriptor("lookup_capability");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.read_write_class === "READ_ONLY", d.descriptor!.read_write_class);
    assert(d.descriptor!.execution_mode === "READ_ONLY", d.descriptor!.execution_mode);
    assert(d.descriptor!.forbidden_operations.includes("direct_provider_credential_read"), "forbid");
  });

  check("4. missing / unknown capability path fails closed", () => {
    const missing = resolveToolDescriptor("totally.unknown.tool");
    assert(missing.status === "UNKNOWN_TOOL", missing.status);
  });

  check("5. missing connector fails closed (no invented connector)", () => {
    setMcpIngressCheck(() => false);
    const missing = resolveToolDescriptor("get_system_status");
    assert(missing.status === "CONNECTOR_UNAVAILABLE", missing.status);
    setMcpIngressCheck(() => true);
    const d = resolveToolDescriptor("get_system_status");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.connector_ref!.includes("connection-registry"), d.descriptor!.connector_ref!);
  });

  check("6. missing schema reference fails closed", () => {
    const d = resolveToolDescriptor("submit_command");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.schema_ref.length > 0, "schema");
  });

  check("7. unknown tool_id fails closed", () => {
    const d = resolveToolDescriptor("not.a.real.tool");
    assert(d.status === "UNKNOWN_TOOL", d.status);
    assert(d.descriptor === null, "no descriptor");
  });

  check("8. revoked tool fails closed", () => {
    assert(isRawRailwayMcpTool("railway_deploy"), "raw listed");
    const d = resolveToolDescriptor("railway_deploy");
    assert(d.status === "REVOKED_TOOL", d.status);
  });

  check("9. tool resolves existing canonical capability registration ref", () => {
    const d = resolveToolDescriptor("dna_os.list_local_resources");
    // may be CAPABILITY_NOT_AVAILABLE if local-resource-access not CONNECTED in this checkout
    assert(d.status === "RESOLVED" || d.status === "CAPABILITY_NOT_AVAILABLE", d.status);
    if (d.status === "RESOLVED") {
      assert(d.descriptor!.capability_id === "local-resource-access", "cap");
      assert(d.descriptor!.registration_ref!.includes("command-router"), "reg");
    }
  });

  check("10. tool resolves existing connector rather than duplicating it", () => {
    const d = resolveToolDescriptor("submit_command");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.runtime_ref.includes("dna-os-http-client"), d.descriptor!.runtime_ref);
  });

  check("11. tool returns evidence reference", () => {
    const d = resolveToolDescriptor("submit_work_result");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.evidence_ref.length > 0, "evidence");
  });

  check("12. privileged action requires Owner approval", () => {
    assert(requiresOwnerDeviceApproval("submit_command") === true, "submit needs approval policy");
    assert(requiresOwnerDeviceApproval("lookup_capability") === false, "read no approval");
  });

  check("13. wrong approval scope fails", () => {
    const bad = assertApprovalScopeExact({
      approved_action: "MERGE_PR",
      approved_tool_id: "submit_command",
      approved_head: "aaa",
      requested_action: "MERGE_PR",
      requested_tool_id: "submit_work_result",
      requested_head: "aaa",
    });
    assert(bad.ok === false, "mismatch");
  });

  check("14+15. exact approval permits exact action only", () => {
    const ok = assertApprovalScopeExact({
      approved_action: "MERGE_PR",
      approved_tool_id: "submit_command",
      approved_head: "a1e4c30",
      requested_action: "MERGE_PR",
      requested_tool_id: "submit_command",
      requested_head: "a1e4c30",
    });
    assert(ok.ok === true, "exact");
    const expiredHead = assertApprovalScopeExact({
      approved_action: "MERGE_PR",
      approved_tool_id: "submit_command",
      approved_head: "old",
      requested_action: "MERGE_PR",
      requested_tool_id: "submit_command",
      requested_head: "new",
    });
    assert(expiredHead.ok === false, "head mismatch");
  });

  check("16+17+18. client receives no raw secret", () => {
    const grant = resolveToolGrant({ caller: INTERNAL });
    const blob = JSON.stringify(grant);
    assert(!/password\s*[:=]|private[_-]?key|ghp_[A-Za-z0-9]{10,}|github_pat_|service_role/i.test(blob), "no secrets");
    assert(grant.secrets_exposed === false, "flag");
  });

  check("19. runtime errors remain bounded by tool contract", () => {
    const d = resolveToolDescriptor("");
    assert(d.status === "UNKNOWN_TOOL", d.status);
  });

  check("20. unknown client cannot obtain privileged tools", () => {
    assert(canInvoke("submit_command", UNAUTH).allowed === false, "invoke denied");
  });

  check("21. source revision is attached to descriptor", () => {
    const d = resolveToolDescriptor("get_task");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.source_revision_ref.includes("runtime-revision"), d.descriptor!.source_revision_ref);
  });

  check("22+23. schema/documentation owners are referenced", () => {
    assert(CANONICAL_OWNERS.schema_owner.includes("canonical-information"), CANONICAL_OWNERS.schema_owner);
    assert(CANONICAL_OWNERS.connector_registry.includes("connection-registry"), CANONICAL_OWNERS.connector_registry);
    const d = resolveToolDescriptor("dna_os.resolve_tool_grant");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
  });

  check("24. ChatGPT/Claude/client identity does not alter governance", () => {
    const a = resolveToolGrant({ caller: { ...UNAUTH, client_id: "chatgpt" } });
    const b = resolveToolGrant({ caller: { ...UNAUTH, client_id: "claude" } });
    assert(a.client_vendor_independent && b.client_vendor_independent, "independent");
    assert(a.grants.map((g) => g.tool_id).sort().join(",") === b.grants.map((g) => g.tool_id).sort().join(","), "same");
  });

  check("25. MCP handler path remains DNA OS transport authority", () => {
    const d = resolveToolDescriptor("submit_command");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.runtime_ref.includes("8791"), d.descriptor!.runtime_ref);
    assert(d.descriptor!.forbidden_operations.includes("bypass_dna_os_http_transport"), "no bypass");
  });

  check("policy for new grant tools is EXTERNAL_ALLOWED read-only", () => {
    assert(policyFor("dna_os.resolve_tool_grant").export_class === "EXTERNAL_ALLOWED", "policy");
    assert(policyFor("dna_os.inspect_tool_descriptor").read_write_class === "READ_ONLY", "ro");
  });

  check("VERIFICATION_READ_ONLY scope excludes mutating tools", () => {
    const grant = resolveToolGrant({ caller: INTERNAL, task_scope: "VERIFICATION_READ_ONLY" });
    assert(grant.grants.every((g) => g.descriptor.read_write_class === "READ_ONLY"), "all read");
  });

  check("conceptual aliases resolve to existing tools (no duplicates)", () => {
    assert(resolveCanonicalToolId("dnaos.lookup_capability") === "lookup_capability", "alias");
    assert(Object.keys(CONCEPTUAL_TOOL_ALIASES).length >= 10, "alias map");
    const d = resolveToolDescriptor("dnaos.lookup_capability");
    assert(d.status === "RESOLVED" && d.descriptor, d.reason);
    assert(d.descriptor!.tool_id === "lookup_capability", d.descriptor!.tool_id);
    assert(d.descriptor!.resolved_from_alias === "dnaos.lookup_capability", "from alias");
    assert(d.descriptor!.tool_surface_class === "OPERATIONAL", d.descriptor!.tool_surface_class);
  });

  check("grant accepts conceptual alias for requested_tool_id", () => {
    const grant = resolveToolGrant({ caller: INTERNAL, requested_tool_id: "dnaos.get_task" });
    assert(grant.status === "GRANTED_SET", grant.reason);
    assert(grant.grants.length === 1 && grant.grants[0]!.tool_id === "get_task", "mapped");
  });

  check("drift detection reports ALIGNED for fixture + explicit policies", () => {
    const drift = detectCanonicalToolingDrift();
    assert(drift.status === "ALIGNED", drift.reason);
    assert(drift.mcp_ingress_declared === true, "ingress");
  });

  check("undeclared policy tool fails closed as OUT_OF_SYNC", () => {
    setRegisteredToolsProvider(() => [
      ...FIXTURE_TOOLS,
      { metadata: { name: "dna_os.fake_undeclared_tool", title: "Fake", description: "should drift", read_write: "read", permission_scope: "system-status", evidence_behavior: "none", dna_os_capability_id: null } },
    ]);
    const d = resolveToolDescriptor("dna_os.fake_undeclared_tool");
    assert(d.status === "OUT_OF_SYNC", d.status);
    const drift = detectCanonicalToolingDrift();
    assert(drift.status === "OUT_OF_SYNC", drift.reason);
    assert(drift.undeclared_policy_tools.includes("dna_os.fake_undeclared_tool"), "listed");
    setRegisteredToolsProvider(() => FIXTURE_TOOLS);
  });

  setRegisteredToolsProvider(null);
  setMcpIngressCheck(null);
  console.log(`\n${passed} passed, ${failed} failed`);
  if (failed > 0) process.exitCode = 1;
}

main();
