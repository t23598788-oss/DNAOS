#!/usr/bin/env node
/**
 * หน้าที่: LISTENING OBSERVATION MODE — real microphone audio -> real
 * STT (SAME unchanged binary/model as ./whisper-listener.mjs:
 * `/opt/homebrew/bin/whisper-stream` + `/Users/tam/whisper-models/
 * ggml-base.bin`, no VAD/model change) -> transcript recorded to a log
 * file and printed live. This file NEVER imports or calls
 * ./intent-resolver.ts, ./dispatcher.ts, ./contract.ts,
 * ./runtime-server.ts, or any Command Router / OS Action path — it has
 * no socket client, no subprocess dispatch, nothing but STT capture and
 * logging. Words like "อ่าน"/"หยุด"/"เปิด"/"ปิด" are treated as plain
 * text here, never as commands.
 *
 * Transcript text is recorded exactly as whisper-stream produced it — no
 * dialect filtering, no spelling correction, no LLM rewrite.
 *
 * Real original-audio evidence (2026-08-21 addition, Owner instruction):
 * whisper-stream has its own real, existing `-sa`/`--save-audio` flag
 * (confirmed via `--help` and a real 6s test recording — writes ONE
 * continuous 16000 Hz / mono / Int16 PCM WAV to its cwd, filename
 * `<local-time>.wav`, auto-generated by the binary itself) — reused
 * as-is, not a new parallel recorder. This process's cwd is set to a
 * dedicated, empty-at-start `audioDir` per session so that file is the
 * ONE wav in it, easy to find afterward. `MIC_AUDIO_START`'s
 * `recorded_at` is the real-time anchor for sample offset 0 in that wav;
 * any later `RAW_UPDATE`'s `elapsed_since_start_ms` maps to a sample
 * offset via `elapsed_ms * 16` (16000 Hz -> 16 samples/ms) — this is what
 * lets a later offline pass answer "what did the mic actually pick up
 * here" without trusting the transcript alone.
 *
 * Input: real microphone audio via whisper-stream's own SDL2 capture.
 * Output: append-only JSONL at LOG_PATH (one object per raw transcript
 * update: recorded_at, sequence, transcript, confidence, elapsed_ms,
 * source/model) + the same lines echoed live to stdout; the real audio
 * WAV written by whisper-stream itself under `audioDir`.
 * Dependency ที่อนุญาต: node:child_process (spawn whisper-stream only),
 * node:fs.
 */
import { spawn } from "node:child_process";
import { appendFileSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";

const repoRoot = "/Users/tam/Desktop/DNA-OS-INFRASTRUCTURE";
const whisperBin = "/opt/homebrew/bin/whisper-stream";
const modelPath = "/Users/tam/whisper-models/ggml-base.bin";
const dataDir = join(repoRoot, "connections/voice-command/data");
const LOG_PATH = join(repoRoot, "connections/voice-command/listen-observation.log");
const sessionStamp = new Date().toISOString().replace(/[:.]/g, "-");
const audioDir = join(dataDir, "observation-audio", sessionStamp);

mkdirSync(dataDir, { recursive: true });
mkdirSync(audioDir, { recursive: true });

function nowMs() { return Date.now(); }
function stripAnsi(s) { return s.replace(/\x1b\[[0-9;]*[A-Za-z]/g, "").replace(/\r/g, "\n"); }

function writeEntry(entry) {
  const line = `${JSON.stringify(entry)}\n`;
  appendFileSync(LOG_PATH, line, "utf-8");
  process.stdout.write(`[${entry.recorded_at}] seq=${entry.sequence} elapsed_ms=${entry.elapsed_since_start_ms ?? "NA"} transcript=${entry.transcript}\n`);
}

let sequence = 0;
let lastRawText = "";
let micAudioStartMs = null;

const startedAt = new Date().toISOString();
writeEntry({
  recorded_at: startedAt,
  sequence: sequence++,
  kind: "SESSION_START",
  transcript: null,
  confidence: null,
  elapsed_since_start_ms: 0,
  source: "whisper-stream",
  model: modelPath,
  audio_dir: audioDir,
  audio_format: "wav, 1ch, 16000Hz, Int16 (whisper-stream's own -sa output)",
});

const args = ["-m", modelPath, "-l", "th", "-t", "4", "-sa"];
const child = spawn(whisperBin, args, { cwd: audioDir });

child.stdout.on("data", (chunk) => {
  const text = stripAnsi(chunk.toString("utf8"));
  for (const rawLine of text.split("\n")) {
    if (rawLine.includes("Start speaking") && micAudioStartMs === null) {
      micAudioStartMs = nowMs();
      const audioFile = readdirSync(audioDir).find((f) => f.endsWith(".wav")) ?? null;
      writeEntry({
        recorded_at: new Date().toISOString(),
        sequence: sequence++,
        kind: "MIC_AUDIO_START",
        transcript: null,
        confidence: null,
        elapsed_since_start_ms: 0,
        source: "whisper-stream",
        model: modelPath,
        audio_file: audioFile ? join(audioDir, audioFile) : null,
        note: "sample_offset for any later elapsed_since_start_ms = round(elapsed_ms * 16)",
      });
      continue;
    }
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed === lastRawText) continue;
    lastRawText = trimmed;
    // whisper-stream does not expose a distinct final/partial marker or a
    // per-token confidence value — every raw update it prints is recorded
    // here, honestly labeled, rather than inventing a partial/final
    // classification or a fabricated confidence number.
    writeEntry({
      recorded_at: new Date().toISOString(),
      sequence: sequence++,
      kind: "RAW_UPDATE",
      transcript: trimmed,
      confidence: null,
      elapsed_since_start_ms: micAudioStartMs !== null ? nowMs() - micAudioStartMs : null,
      source: "whisper-stream",
      model: modelPath,
    });
  }
});
child.stderr.on("data", () => {}); // real whisper.cpp diagnostic/model-load noise, not part of the transcript record.
child.on("exit", (code) => {
  writeEntry({
    recorded_at: new Date().toISOString(),
    sequence: sequence++,
    kind: "WHISPER_STREAM_EXITED",
    transcript: null,
    confidence: null,
    elapsed_since_start_ms: micAudioStartMs !== null ? nowMs() - micAudioStartMs : null,
    source: "whisper-stream",
    model: modelPath,
    exit_code: code,
  });
});

function shutdown() {
  const endedAt = new Date().toISOString();
  writeEntry({
    recorded_at: endedAt,
    sequence: sequence++,
    kind: "SESSION_END",
    transcript: null,
    confidence: null,
    elapsed_since_start_ms: micAudioStartMs !== null ? nowMs() - micAudioStartMs : null,
    source: "whisper-stream",
    model: modelPath,
  });
  child.kill("SIGTERM");
  process.exit(0);
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
