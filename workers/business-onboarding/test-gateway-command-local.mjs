async function api(path, body, token, admin = false) {
  const key = admin ? vars.SERVICE_ROLE_KEY : vars.ANON_KEY;
  const response = await fetch(vars.API_URL + path, { method: 'POST', headers: {
    apikey: key, 'content-type': 'application/json', ...(token || admin ? { authorization: `Bearer ${token || key}` } : {}),
  }, body: JSON.stringify(body) });
  return { response, data: await response.json() };
}
